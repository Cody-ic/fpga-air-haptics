"""Frozen sequence geometry and offline pressure-frame compilation.

No serial port, output command, interpolated hand annotation or invented
pressure measurement is generated by this module.
"""
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import numpy as np

from .egopressure import counts_to_kpa, display_points
from .hand_pose import palm_frame_from_joints, geometric_bends_deg
from .pressure import PressureMapping, compile_pressure


def _indices(sequence, indices):
    values = list(range(len(sequence.frames))) if indices is None else list(indices)
    if not values or any(type(i) not in (int, np.int64, np.int32) or not 0 <= i < len(sequence.frames) for i in values):
        raise ValueError('序列帧索引无效')
    if len(set(map(int, values))) != len(values):
        raise ValueError('帧索引不能重复')
    return [int(i) for i in values]


def fit_sequence_mapping(sequence, indices=None, *, span_mm=40., threshold_kpa=1., trim_fraction=.01):
    """Fit a fixed map using pressure-weighted 1%..99% marginal bounds.

    Tiny isolated noise cannot re-scale each frame. The fixed map is a material
    mapping, not an estimate of the actual user's hand location.
    """
    if not np.isfinite([span_mm, threshold_kpa, trim_fraction]).all() or not 5 <= span_mm <= 80 or threshold_kpa < 0 or not 0 <= trim_fraction < .1:
        raise ValueError('序列映射参数无效')
    xs, ys = np.zeros(185), np.zeros(105)
    for i in _indices(sequence, indices):
        if not sequence.pressure_valid[i]:
            continue
        pressure = counts_to_kpa(sequence.force[i]).astype(float)
        weight = np.where(pressure > threshold_kpa, pressure, 0)
        xs += weight.sum(0)
        ys += weight.sum(1)
    if xs.sum() <= 0:
        raise ValueError('所选序列没有有效接触压力')
    def bounds(weights, coordinates):
        cumulative = np.cumsum(weights)/weights.sum()
        lo = min(int(np.searchsorted(cumulative, trim_fraction, side='right')), len(weights)-1)
        hi = min(int(np.searchsorted(cumulative, 1-trim_fraction, side='left')), len(weights)-1)
        return sorted((float(coordinates[lo]), float(coordinates[hi])))
    x = (np.linspace(-120, 120, 186)[:-1]+np.linspace(-120, 120, 186)[1:])/2
    y = (np.linspace(68.75, -68.75, 106)[:-1]+np.linspace(68.75, -68.75, 106)[1:])/2
    xb, yb = bounds(xs, x), bounds(ys, y)
    origin = ((xb[0]+xb[1])/2, (yb[0]+yb[1])/2)
    scale = span_mm/max(xb[1]-xb[0], yb[1]-yb[0], 1.25)
    return PressureMapping(origin, float(scale), float(span_mm)).validate()


def hand_features(sequence, index):
    if not sequence.hand_valid[index]:
        return dict(valid=False, reason='missing_annotation', live_tracking=False)
    joints = display_points(sequence.joints[index]).astype(float)
    try:
        frame = palm_frame_from_joints(joints, sequence.hand_side)
    except ValueError as error:
        return dict(valid=False, reason=str(error), live_tracking=False)
    return dict(valid=True, palm=frame.metadata(),
                local_joints_mm=frame.local_mm(joints).tolist(),
                geometric_bends_deg=geometric_bends_deg(joints), live_tracking=False)


def compile_sequence_frame(sequence, index, array, *, mapping=None, **options):
    _indices(sequence, [index])
    if not sequence.pressure_valid[index]:
        raise ValueError('此帧缺失压力数据')
    mapping = mapping or fit_sequence_mapping(sequence, span_mm=options.get('span_mm', 40.))
    result = compile_pressure(counts_to_kpa(sequence.force[index]), array, mapping=mapping, **options)
    result.mapping.update(sequence_name=sequence.name, source_frame=int(sequence.frames[index]),
                          sequence_mapping=True, hand_features=hand_features(sequence, index))
    return result


def sequence_summary(sequence, mapping=None, *, span_mm=40.):
    # A joint-only grasp has no pressure-pad registration. Even an all-zero
    # valid pressure sequence can be analysed without inventing a mapping.
    pressure_available = bool(sequence.pressure_valid.any())
    if not pressure_available and mapping is not None:
        raise ValueError('无压力测量的数据不能指定压力映射')
    if mapping is None and any(np.any(counts_to_kpa(sequence.force[i]) > 1.)
                               for i in np.flatnonzero(sequence.pressure_valid)):
        mapping = fit_sequence_mapping(sequence, span_mm=span_mm)
    if mapping is not None:
        mapping.validate()
    rows = []
    x = (np.linspace(-120, 120, 186)[:-1]+np.linspace(-120, 120, 186)[1:])/2
    y = (np.linspace(68.75, -68.75, 106)[:-1]+np.linspace(68.75, -68.75, 106)[1:])/2
    for i, frame_id in enumerate(sequence.frames):
        row = dict(frame=int(frame_id), time_s=float(sequence.seconds[i]),
                   pressure_valid=bool(sequence.pressure_valid[i]), hand=hand_features(sequence, i))
        if sequence.pressure_valid[i]:
            pressure = counts_to_kpa(sequence.force[i]).astype(float)
            total = float(pressure.sum())
            row.update(total_contact_force_n=float(sequence.total_force_n[i]), peak_contact_kpa=float(pressure.max()))
            if total > 0 and mapping is not None:
                centre = np.array([np.dot(pressure.sum(0), x), np.dot(pressure.sum(1), y)])/total
                row['mapped_pressure_centre_mm'] = ((centre-mapping.origin_display_mm)*mapping.scale).tolist()
        rows.append(row)
    return dict(format='touchsee-hand-sequence-analysis-1', dataset=sequence.source_dataset,
                source_name=sequence.name, hand_side=sequence.hand_side,
                mapping=asdict(mapping) if mapping is not None else None, rows=rows, live_tracking=False,
                pressure_kind='contact_sensor_kpa' if pressure_available else 'absent',
                field_kind='theoretical' if pressure_available else 'not_generated')


def compile_sequence_plan(sequence, indices, array, *, mapping=None, max_frames=24, **options):
    indices = _indices(sequence, indices)
    if type(max_frames) is not int or not 1 <= max_frames <= 120 or len(indices) > max_frames:
        raise ValueError('单次最多生成指定数量的离线帧，默认24帧')
    if any(b <= a for a, b in zip(indices, indices[1:])):
        raise ValueError('导出帧须按时间递增')
    mapping = mapping or fit_sequence_mapping(sequence, span_mm=options.get('span_mm', 40.))
    rows = []
    for index in indices:
        row = dict(frame=int(sequence.frames[index]), time_s=float(sequence.seconds[index]))
        if not sequence.pressure_valid[index] or not np.any(counts_to_kpa(sequence.force[index]) > 1):
            row.update(status='skipped', reason='missing_pressure_or_no_contact')
        else:
            result = compile_sequence_frame(sequence, index, array, mapping=mapping, **options)
            raw = np.ascontiguousarray(sequence.force[index], dtype='<f4')
            row.update(status='compiled', config=result.config.wire(), metrics=result.metrics,
                       hand=hand_features(sequence, index), raw_counts_sha256=hashlib.sha256(raw.tobytes()).hexdigest())
        rows.append(row)
    return dict(format='touchsee-pressure-sequence-plan-1', source_name=sequence.name,
                array=array.wire(), mapping=asdict(mapping), frames=rows,
                automatic_device_playback=False, simulation_only=True,
                semantics='independent_static_phase_frames_not_a_hardware_sequence_player')


def save_analysis(document, path):
    path = Path(path)
    path.write_text(json.dumps(document, ensure_ascii=False, indent=2, allow_nan=False), encoding='utf-8')


def main():
    import argparse
    from .egopressure import load_sequence, sample_path
    from .model import ArraySpec
    parser = argparse.ArgumentParser(description='离线分析手姿与压力序列，或生成独立静态相位帧；不连接设备')
    parser.add_argument('--input', type=Path, default=sample_path())
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--compile-frames', type=int, default=0, help='均匀选取的离线帧数，0只导出序列分析')
    parser.add_argument('--span-mm', type=float, default=40)
    parser.add_argument('--z-mm', type=float, default=50)
    args = parser.parse_args()
    if not 0 <= args.compile_frames <= 24:
        parser.error('--compile-frames must be 0..24')
    sequence = load_sequence(args.input)
    if args.compile_frames:
        mapping = fit_sequence_mapping(sequence, span_mm=args.span_mm)
        valid = np.flatnonzero(sequence.pressure_valid)
        indices = valid[np.linspace(0, len(valid)-1, min(args.compile_frames, len(valid))).astype(int)].tolist()
        document = compile_sequence_plan(sequence, indices, ArraySpec(8, 8, 10300), mapping=mapping,
                                         z_mm=args.z_mm, span_mm=args.span_mm)
    else:
        document = sequence_summary(sequence, span_mm=args.span_mm)
    save_analysis(document, args.output)
    print(args.output)


if __name__ == '__main__':
    main()
